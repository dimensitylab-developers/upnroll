"use client";

import { useState } from "react";
import { Chapter, FixtureBadge } from "../chapter";
import { Badge } from "@/components/ui/badge";
import { previewBracket } from "@/lib/preview/fixtures";
import { cn } from "@/lib/utils";

const statusColor: Record<string, string> = {
  COMPLETED: "text-muted-foreground",
  IN_PROGRESS: "text-brand-cyan",
  SCHEDULED: "text-foreground",
  PENDING: "text-muted-foreground/50",
};

export function Brackets() {
  const [selected, setSelected] = useState<string | null>(null);

  return (
    <Chapter id="brackets" title="Tournament Brackets" subtitle="Deterministic fictional single-elimination bracket. Format shown is a baseline only — not an approved rule (see OD-003).">
      <div className="flex items-center justify-between mb-4">
        <p className="font-semibold">{previewBracket.divisionName}</p>
        <Badge className="bg-brand-cyan/20 text-brand-cyan border-brand-cyan/40">
          <span className="size-1.5 rounded-full bg-brand-cyan live-pulse mr-1.5" /> 1 match live
        </Badge>
      </div>

      <div className="overflow-x-auto pb-4">
        <div className="flex gap-8 min-w-max">
          {previewBracket.rounds.map((round) => (
            <div key={round.name} className="flex flex-col gap-4 justify-center">
              <p className="text-xs uppercase tracking-widest text-muted-foreground text-center">{round.name}</p>
              <div className="flex flex-col gap-6 justify-around flex-1">
                {round.matches.map((m) => (
                  <button
                    key={m.id}
                    onClick={() => setSelected(m.id)}
                    className={cn(
                      "manga-panel w-48 p-3 text-left text-sm",
                      selected === m.id && "ring-2 ring-primary",
                      m.status === "IN_PROGRESS" && "border-brand-cyan/50"
                    )}
                  >
                    <div className={cn("flex justify-between", m.winner === m.a && "text-foreground font-medium")}>
                      <span>{m.a}</span>
                      {m.winner === m.a && <span className="text-brand-gold text-xs">W</span>}
                    </div>
                    <div className="h-px bg-white/10 my-1.5" />
                    <div className={cn("flex justify-between", m.winner === m.b && "text-foreground font-medium")}>
                      <span>{m.b}</span>
                      {m.winner === m.b && <span className="text-brand-gold text-xs">W</span>}
                    </div>
                    <p className={cn("text-xs mt-2", statusColor[m.status])}>{m.status.replace("_", " ")}</p>
                  </button>
                ))}
              </div>
            </div>
          ))}
        </div>
      </div>
      <FixtureBadge>Bracket structure and results are fictional and fixed — not generated by a real engine yet</FixtureBadge>
    </Chapter>
  );
}
